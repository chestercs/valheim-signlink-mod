"""The glyph palette of SignLink's text templates (2 Content › Text: Block, Label, Symbol, Pattern), written as C#.

Reads out/glyphs.json (extract_glyphs.py: every glyph of the game's font assets with its advance and bounding box
in em, its font, and the fonts' TMP ascender, descender and faux-bold growth) and writes
mod/SignLink/Pictures/GlyphData.cs: the groups the Symbol palette shows, the letters a Label may use, and the
metrics of all of them. No JSON parser in the mod, and the tests compile the same file.

    ./sign.sh palette        (sign.sh: run "$IMG" python palette.py)

A glyph the fonts lack is left out with a note; the C# side has no silent fallbacks.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GLYPHS = os.path.join(HERE, "out", "glyphs.json")
OUT = os.path.join(HERE, "..", "mod", "SignLink", "Pictures", "GlyphData.cs")

# The Symbol palette: a few of each, all present in the game's fonts (checked here). Emoji are line art in the
# game's NotoEmoji font.
GROUPS = [
    ("Arrows", "←↑→↓↔↕⇦⇧⇨⇩⬅⬆⬇"),
    ("Shapes", "●○■□▲△▼▽◆◇★☆✚✖◉◎◐◑"),
    ("Frames", "═║╔╗╚╝╠╣╦╩╬─│┌┐└┘├┤┬┴┼▀▄▌▐█▓▒░▚▞"),
    ("Runes", "ᚠᚢᚦᚨᚱᚲᚷᚹᚺᚾᛁᛃᛇᛈᛉᛊᛏᛒᛖᛗᛚᛜᛞᛟ"),
    ("Symbols", "♥♦♣♠☠⚔⚒⚓☀☁☂❄⚡♪♫☕⚠☢☣✔⚙☺☹✿❀☘⚜"),
    ("Emoji", "🐺🐉🐗🦌🐟🐝🐍🦇🏹🛡🔥💀🌲⛵🍖🍺🪓⛏🗡🧭🔑💎🌙⭐"),
]
# A Label's letters (the Norse font: Latin, Latin-1 with the Hungarian accents) and the Pattern's glyphs.
LETTERS = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;!?-+=/()'\"&%*#@<>"
           "ÁÉÍÓÖŐÚÜŰáéíóöőúüűÄäÖöÜüßÀàÈèÌìÒòÙùÂâÊêÎîÔôÛûÇçÑñ")
PATTERN = "█▓▒░■●◆▚"
BLOCK = "■"


def chars(s: str) -> list[str]:
    """Code points (an emoji is a surrogate pair in C#; one string each)."""
    return list(s)


def cs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    with open(GLYPHS, encoding="utf-8") as f:
        db = json.load(f)
    fonts, glyphs = db["fonts"], db["glyphs"]
    wanted: list[str] = []
    groups_out = []
    missing = []
    for name, s in GROUPS:
        have = [c for c in chars(s) if c in glyphs]
        missing += [c for c in chars(s) if c not in glyphs]
        groups_out.append((name, have))
        wanted += have
    for c in chars(LETTERS) + chars(PATTERN) + [BLOCK]:
        if c in glyphs:
            wanted.append(c)
        else:
            missing.append(c)
    seen = set()
    wanted = [c for c in wanted if not (c in seen or seen.add(c))]
    used_fonts = sorted({glyphs[c]["f"] for c in wanted})

    lines = []
    w = lines.append
    w("// Generated by signart/palette.py from signart/out/glyphs.json (the game's font assets): do not edit by hand.")
    w("// The glyphs SignLink's text templates place exactly (Pictures/Snippets.cs): their advance and bounding box in")
    w("// em, their font's TMP ascender, descender and faux-bold growth. No Unity here (mod/SignLink.Tests).")
    w("using System.Collections.Generic;")
    w("")
    w("namespace SignLink.Pictures")
    w("{")
    w("    internal static class GlyphData")
    w("    {")
    w("        public sealed class Font")
    w("        {")
    w("            public readonly string Name;")
    w("            public readonly double A, D, Bold;")
    w("            public Font(string name, double a, double d, double bold) { Name = name; A = a; D = d; Bold = bold; }")
    w("        }")
    w("")
    w("        public sealed class Glyph")
    w("        {")
    w("            public readonly string Ch, Name;")
    w("            public readonly double Adv, X0, Y0, X1, Y1;")
    w("            public readonly Font Font;")
    w("            public Glyph(string ch, double adv, double x0, double y0, double x1, double y1, Font font, string name)")
    w("            { Ch = ch; Adv = adv; X0 = x0; Y0 = y0; X1 = x1; Y1 = y1; Font = font; Name = name; }")
    w("        }")
    w("")
    for fn in used_fonts:
        fd = fonts[fn]
        w(f"        public static readonly Font {fn.capitalize()} = new Font({cs_str(fn)}, {fd['A']!r}, {fd['D']!r}, {fd['bold']!r});")
    w("")
    w("        /// <summary>The Symbol palette's groups, in the order shown.</summary>")
    w("        public static readonly string[] GroupNames = { " + ", ".join(cs_str(n) for n, _ in groups_out) + " };   // lang:keys")
    w("        public static readonly string[][] Groups =")
    w("        {")
    for name, have in groups_out:
        w("            new[] { " + ", ".join(cs_str(c) for c in have) + " },")
    w("        };")
    w("        /// <summary>The Pattern's glyphs, and the Block's.</summary>")
    w("        public static readonly string[] PatternGlyphs = { " + ", ".join(cs_str(c) for c in chars(PATTERN) if c in glyphs) + " };")
    w(f"        public const string Block = {cs_str(BLOCK)};")
    w("")
    w("        public static readonly Glyph[] Glyphs =")
    w("        {")
    for c in wanted:
        g = glyphs[c]
        x0, y0, x1, y1 = g["bb"]
        w(f"            new Glyph({cs_str(c)}, {g['adv']!r}, {x0!r}, {y0!r}, {x1!r}, {y1!r}, {g['f'].capitalize()}, {cs_str(g['n'])}),")
    w("        };")
    w("")
    w("        static Dictionary<string, Glyph> byChar;")
    w("")
    w("        /// <summary>The glyph's metrics, or null when the templates do not know it.</summary>")
    w("        public static Glyph Find(string ch)")
    w("        {")
    w("            if (byChar == null)")
    w("            {")
    w("                var d = new Dictionary<string, Glyph>();")
    w("                foreach (Glyph g in Glyphs) d[g.Ch] = g;")
    w("                byChar = d;")
    w("            }")
    w("            return ch != null && byChar.TryGetValue(ch, out Glyph found) ? found : null;")
    w("        }")
    w("    }")
    w("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(wanted)} glyphs in {len(groups_out)} groups, fonts {', '.join(used_fonts)} -> {os.path.relpath(OUT, HERE)}")
    if missing:
        print("left out (not in the game's fonts): " + "".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
